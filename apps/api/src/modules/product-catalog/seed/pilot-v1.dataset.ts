function usda(n: Omit<SeedNutrition, 'source' | 'sourceRef' | 'confidenceLabel'>): SeedNutrition {
  return {
    ...n,
    fiber: n.fiber ?? null,
    sodium: n.sodium ?? null,
    source: 'IMPORT',
    sourceRef: 'USDA_FDC',
    confidenceLabel: 'source-provided',
  };
}

function rf(n: Omit<SeedNutrition, 'source' | 'sourceRef' | 'confidenceLabel'>): SeedNutrition {
  return {
    ...n,
    fiber: n.fiber ?? null,
    sodium: n.sodium ?? null,
    source: 'IMPORT',
    sourceRef: 'RF_FOOD_COMPOSITION_REF',
    confidenceLabel: 'needs-review',
  };
}

function fixture(n: Omit<SeedNutrition, 'source' | 'sourceRef' | 'confidenceLabel'>): SeedNutrition {
  return {
    ...n,
    fiber: n.fiber ?? null,
    sodium: n.sodium ?? null,
    source: 'FIXTURE',
    sourceRef: 'STEP092_093_FIXTURE',
    confidenceLabel: 'source-provided',
  };
}

function p(
  partial: Omit<ProductSeedRecord, 'status' | 'seedProvenance'> & {
    sources: string[];
    notes?: string;
  },
): ProductSeedRecord {
  const { sources, notes, ...rest } = partial;
  return {
    ...rest,
    status: 'ACTIVE',
    seedProvenance: { datasetVersion: DS, sources, notes },
  };
}

