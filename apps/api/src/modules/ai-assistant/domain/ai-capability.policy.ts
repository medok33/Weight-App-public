import type { AITariffTier } from './ai-tariff.types';

export function capabilityInstructionFor(tier: AITariffTier): string {
  if (tier === 'FREE') {
    return [
      'Тариф FREE:',
      '- Краткие ответы по питанию, продуктам, тренировкам, прогрессу и привычкам.',
      '- Простая тренировка на один день; базовая персонализация по Goal Core.',
      '- Вопросы о знаменитостях: краткий общий ответ; подробная адаптация программы — в Premium.',
      '- Не составляй многонедельные программы без достаточных данных анкеты.',
    ].join('\n');
  }
  return [
    'Тариф PREMIUM/OWNER:',
    '- Доступны подробные программы, глубокий анализ, сравнение методик,',
    '  известные спортсмены/культуристы, адаптация под Goal Core и оборудование.',
    '- Celebrity intents разрешены; отделяй факты, неопределённость и адаптацию.',
  ].join('\n');
}
